test('email signup opens identity step and unconfigured social providers stay disabled', async ({ page }) => {
  const email = `signup-${randomUUID()}@example.test`
  await page.goto('/')
  await expect(page.getByRole('button', { name: 'Google로 계속하기 (연결 준비 중)' })).toBeDisabled()
  await expect(page.getByRole('button', { name: '카카오로 계속하기 (연결 준비 중)' })).toBeDisabled()
  await page.getByRole('button', { name: '회원가입 화면', exact: true }).click()
  await page.getByLabel('이메일', { exact: true }).fill(email)
  await page.getByLabel('비밀번호', { exact: true }).fill('LocalFixture-Only1!')
  await page.getByLabel('비밀번호 확인', { exact: true }).fill('Mismatch1!')
  await page.getByRole('button', { name: '이메일로 회원가입' }).click()
  await expect(page.getByText('비밀번호 확인이 일치하지 않아요.')).toBeVisible()
  await page.getByLabel('비밀번호 확인', { exact: true }).fill('LocalFixture-Only1!')
  const signupResponse = page.waitForResponse(response => new URL(response.url()).pathname.endsWith('/auth/v1/signup') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '이메일로 회원가입' }).click()
  const created = await (await signupResponse).json()
  const data = fixture()
  data.users.push({ id: created.user?.id ?? created.id, email, password: 'LocalFixture-Only1!' })
  writeFileSync(path.resolve('../.local/member-e2e.json'), JSON.stringify(data))
  await expect(page.getByLabel('이름 (필수)', { exact: true })).toBeVisible()
})

test('operator publishes a real slot and immutable consent version with server role checks', async ({ page, request }) => {
  const data = fixture()
  const operator = data.users[2]
  await page.goto('/admin')
  await page.getByLabel('이메일', { exact: true }).fill(operator.email)
  await page.getByLabel('비밀번호', { exact: true }).fill(operator.password)
  await page.getByRole('button', { name: '로그인', exact: true }).click()
  await expect(page.getByRole('heading', { name: '운영 모집·동의 설정' })).toBeVisible()
  const local = (offset: number) => new Date(Date.now() + offset * 86400000 + 9 * 3600000).toISOString().slice(0,16)
  await page.getByLabel('모집 시작 (KST)').fill(local(-1))
  await page.getByLabel('모집 마감 (KST)').fill(local(18))
  await page.getByLabel('매칭 실행 (KST)').fill(local(19))
  await page.getByLabel('행사 시작 (KST)').fill(local(20))
  await page.getByLabel('모집 지역', { exact: true }).selectOption('gangnam')
  await page.getByRole('button', { name: '모집 초안 생성', exact: true }).click()
  await expect(page.getByText('모집 초안을 만들었어요. 목록에서 확인 후 발행해 주세요.')).toBeVisible()
  await page.getByRole('button', { name: '모집 발행', exact: true }).last().click()
  await expect(page.getByText('모집 공개 상태를 변경했어요.')).toBeVisible()
  await page.getByLabel('동의 버전', { exact: true }).fill(`e2e-${randomUUID()}`)
  await page.getByLabel('문서 제목', { exact: true }).fill('LOCAL TEST ONLY 개인정보')
  await page.getByLabel('동의 전문', { exact: true }).fill('가상 계정 검증용 문서. 실제 운영 동의가 아닙니다.')
  await page.getByRole('checkbox', { name: '전문을 검토했으며 새 필수 동의로 공개하는 것을 확인합니다.' }).check()
  await page.getByRole('button', { name: '필수 동의 발행', exact: true }).click()
  await expect(page.getByText('새 필수 동의 버전을 발행했어요. 기존 수락 이력은 보존돼요.')).toBeVisible()
  await expect(page.locator('body')).toHaveJSProperty('scrollWidth', 390)
  await page.screenshot({ path: 'test-results/operations-mobile.png', fullPage: true })
  const user = data.users[0]
  const login = await request.post(`${data.apiUrl}/auth/v1/token?grant_type=password`, { headers: { apikey: data.publishableKey }, data: { email: user.email, password: user.password } })
  const { access_token: token } = await login.json()
  const headers = { authorization: `Bearer ${token}` }
  const state = await (await request.get(`${data.apiUrl}/functions/v1/member/intake`, { headers })).json()
  const slot = state.slots.find((s: { regionCode: string }) => s.regionCode === 'gangnam')
  expect(slot.matchesAt).toBeTruthy()
  expect(slot.refundCutoffAt).toBeTruthy()
  const draft = await request.put(`${data.apiUrl}/functions/v1/member/intake/draft`, { headers, data: { sourceId: null, input: { slotIds: [slot.id], regions: ['gangnam'], otherRegion: '', ticketCode: 'membership_use' } } })
  expect(draft.status()).toBe(200)
  const revision = (await draft.json()).draft.revision
  const submit = () => request.post(`${data.apiUrl}/functions/v1/member/intake/submit`, { headers, data: { requestKey: randomUUID(), draftRevision: revision } })
  expect((await submit()).status()).toBe(409) // new privacy version must be accepted
  const member = await (await request.get(`${data.apiUrl}/functions/v1/member`, { headers })).json()
  expect((await request.post(`${data.apiUrl}/functions/v1/member/consents`, { headers, data: { documents: member.consentDocuments.filter((d: { required: boolean }) => d.required).map(({ id, version }: { id: string; version: string }) => ({ id, version })) } })).status()).toBe(200)
  const submitted = await submit()
  expect(submitted.status()).toBe(200)
  const app = (await submitted.json()).applications.find((a: { input: { ticketCode: string } }) => a.input.ticketCode === 'membership_use')
  expect(app.paymentStatus).toBe('PAID')
  expect(app.eligible).toBe(true)
})
