import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
import path from 'node:path'

test('participant and operator follow separated menus, preserve a draft and restore direct links', async ({ page }) => {
 const f = JSON.parse(readFileSync(path.resolve('../.local/member-e2e.json'), 'utf8'))
 const login = async (index: number) => {
  await page.getByLabel('이메일', { exact: true }).fill(f.users[index].email)
  await page.getByLabel('비밀번호', { exact: true }).fill(f.users[index].password)
  await page.getByRole('button', { name: '로그인', exact: true }).click()
 }
 await page.goto('/login')
 await login(1)
 await page.getByLabel('이름 (필수)', { exact: true }).fill('흐름 점검 임시 입력')
 expect(await page.locator('.page-nav a').evaluateAll(links => links.every(link => { const r = link.getBoundingClientRect(); return r.width >= 44 && r.height >= 44 }))).toBe(true)
 await page.getByRole('link', { name: '내 식탁', exact: true }).click()
 await expect(page.getByRole('heading', { name: '나의 매칭 상태', exact: true })).toBeVisible()
 await expect(page.getByLabel('이름 (필수)', { exact: true })).toBeHidden()
 await page.getByRole('link', { name: '알림', exact: true }).click()
 await expect(page.getByRole('heading', { name: '나의 매칭 상태', exact: true })).toHaveCount(0)
 expect(await page.locator('.next-action').evaluate(link => link.getBoundingClientRect().height)).toBeGreaterThanOrEqual(44)
 await page.goBack()
 await expect(page.getByRole('heading', { name: '나의 매칭 상태', exact: true })).toBeVisible()
 await page.getByRole('link', { name: '참가 이력', exact: true }).click()
 await expect(page.getByRole('region', { name: '식탁 평가', exact: true })).toBeVisible()
 await expect(page.getByRole('heading', { name: '나의 매칭 상태', exact: true })).toHaveCount(0)
 await page.getByRole('link', { name: '식탁 신청', exact: true }).click()
 await expect(page.getByLabel('이름 (필수)', { exact: true })).toHaveValue('흐름 점검 임시 입력')
 await page.getByRole('link', { name: '계정', exact: true }).click()
 await page.reload()
 await expect(page.getByRole('link', { name: '계정', exact: true })).toHaveAttribute('aria-current', 'page')
 await page.getByRole('button', { name: '로그아웃', exact: true }).click()
 await login(2)
 await page.getByRole('link', { name: '운영 관리', exact: true }).click()
 await expect(page.getByRole('region', { name: '운영 현황', exact: true })).toBeVisible()
 await expect(page.getByRole('button', { name: '3. 회차 신청', exact: true })).toHaveCount(0)
 for (const label of ['모집 준비','자동화 점검','안전·개인정보','현황·조회']) {
  await page.getByRole('button', { name: label, exact: true }).click()
  await expect(page.getByRole('button', { name: label, exact: true })).toHaveAttribute('aria-current', 'page')
 }
 await page.setViewportSize({ width: 320, height: 844 })
 expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
 await page.screenshot({ path: '../.local/service-review-operator.png', fullPage: false })
 await page.getByRole('link', { name: '알림', exact: true }).click()
 await expect(page.getByRole('link', { name: '운영 관리에서 처리 상태 확인', exact: true })).toHaveAttribute('href', '#operations')
 await page.getByRole('link', { name: '운영 관리에서 처리 상태 확인', exact: true }).click()
 await expect(page.getByRole('region', { name: '운영 현황', exact: true })).toBeVisible()
})

